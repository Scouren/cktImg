//! Source-degeneration decks → placed channel orientation and connectivity.
//! Oracle: independent AnalogGenie drawings 769, 770, 771 and 954; the
//! upright clamp counterexamples are 2460 through 2468. No engine form table
//! participates in the expected result.
//!
//! Contents: private pin lookup, then public placement regressions.

const std = @import("std");
const np = @import("NetlistParser");
const support = @import("support.zig");
const testing = std.testing;

const models = "Source degeneration\n.model nch nmos\n.model pch pmos\n";
const pair = "M1 out_a input_a a vss nch\nM2 out_b input_b b vss nch\n" ++
    "I1 a vss 1m\nI2 b vss 1m\n";

// ---- private ----

fn pin(p: *const np.Placed, name: []const u8, k: u32) np.Pt {
    const d = np.checks.deviceIn(p, name).?;
    return p.pin_xy[p.pinRange(d)[0] + k];
}

test "degeneration: six source bridges lie flat while their gain devices stand upright" {
    // Oracle: D/S have equal y in the six source symbols, while M1/M2
    // have equal x. These are the source cards with sizing omitted, not
    // geometry generated by cktImg. Both normal and compact layouts obey.
    const lib = try support.library(testing.allocator);
    defer support.freeLibrary(testing.allocator, lib);
    const cases = [_]struct { deck: []const u8, bridges: []const []const u8 }{
        .{ .deck = models ++
            "I1 VDD net1 DC 1m\nI2 net4 VSS DC 1m\n" ++
            "I3 VDD net5 DC 1m\nI4 net3 VSS DC 1m\n" ++
            "M1 net1 vi+ net0 VSS nch\nM2 net5 vi- net2 VSS nch\n" ++
            "M3 net0 net4 VSS VSS nch\nM4 net2 net3 VSS VSS nch\n" ++
            "M5 VDD net1 net4 VSS nch\nM6 VDD net5 net3 VSS nch\n" ++
            "M7 Iout1 net4 VSS VSS nch\nM8 Iout2 net3 VSS VSS nch\n" ++
            "M9 net2 VC net0 VSS nch\n", .bridges = &.{"m9"} }, // ag-769
        .{ .deck = models ++
            "I1 VDD net2 DC 1m\nI2 net0 VSS DC 1m\n" ++
            "I3 VDD net3 DC 1m\nI4 net1 VSS DC 1m\n" ++
            "M1 net0 vi+ net2 VDD pch\nM2 net1 vi- net3 VDD pch\n" ++
            "M3 net2 net0 VSS VSS nch\nM4 net3 net1 VSS VSS nch\n" ++
            "M5 Iout1 net0 VSS VSS nch\nM6 Iout2 net1 VSS VSS nch\n" ++
            "M7 net3 VC net2 VDD pch\n", .bridges = &.{"m7"} }, // ag-770
        .{ .deck = models ++
            "I1 VCC Iout1 DC 1m\nI2 VCC Iout2 DC 1m\n" ++
            "I3 vx VEE DC 1m\nI4 vy VEE DC 1m\n" ++
            "M1 Iout1 v1 vx VEE nch\nM2 Iout2 v2 vy VEE nch\n" ++
            "M3 vy v1 vx VEE nch\nM4 vx v2 vy VEE nch\n", .bridges = &.{ "m3", "m4" } }, // ag-771
        .{ .deck = models ++
            "M1 net1 Vin+ net2 VSS nch\nM2 iOUT Vin- net0 VSS nch\n" ++
            "M3 net1 net1 VDD VDD pch\nM4 iOUT net1 VDD VDD pch\n" ++
            "M5A net2 VNBias1 VSS VSS nch\nM5B net0 VNBias1 VSS VSS nch\n" ++
            "M6 net2 Vin+ net0 VSS nch\nM7 net2 Vin- net0 VSS nch\n", .bridges = &.{ "m6", "m7" } }, // ag-954
    };
    for (cases) |case| for ([_]bool{ false, true }) |compact| {
        var p = try np.place(testing.allocator, &.{ .layout = .{ .compact = compact } }, lib, &.{case.deck}, null);
        defer p.deinit();
        for (case.bridges) |name| {
            const d = pin(&p, name, 0);
            const s = pin(&p, name, 2);
            try testing.expectEqual(d.y, s.y);
            try testing.expect(d.x != s.x);
            try testing.expect(pin(&p, name, 1).y != d.y);
        }
        for ([_][]const u8{ "m1", "m2" }) |name| {
            try testing.expectEqual(pin(&p, name, 0).x, pin(&p, name, 2).x);
            try testing.expect(pin(&p, name, 0).y != pin(&p, name, 2).y);
        }
        try support.expectConnected(&p, lib);
        try testing.expectEqual(0, try support.shorts(testing.allocator, &p, true));
    };
}

test "degeneration: bridge identity survives channel reversal and card order" {
    // Oracle: reversing a pass channel or renaming/reordering cards cannot
    // change the source-bridge drawing habit. No candidate name is special.
    const lib = try support.library(testing.allocator);
    defer support.freeLibrary(testing.allocator, lib);
    const cases = [_]struct { deck: []const u8, name: []const u8 }{
        .{ .deck = models ++ pair ++ "MX b control a vss nch\n", .name = "mx" },
        .{ .deck = models ++ "MX a control b vss nch\n" ++ pair, .name = "mx" },
        .{ .deck = models ++ "M42 right trim left vss nch\nI2 right vss 1m\nI1 left vss 1m\n" ++
            "M8 output2 signal2 right vss nch\nM7 output1 signal1 left vss nch\n", .name = "m42" },
    };
    for (cases) |case| {
        var p = try np.place(testing.allocator, &.default, lib, &.{case.deck}, null);
        defer p.deinit();
        try testing.expectEqual(pin(&p, case.name, 0).y, pin(&p, case.name, 2).y);
        try testing.expect(pin(&p, case.name, 0).x != pin(&p, case.name, 2).x);
        try support.expectConnected(&p, lib);
        try testing.expectEqual(0, try support.shorts(testing.allocator, &p, true));
    }
}

test "degeneration: clamps and ordinary gain stages retain upright channels" {
    // Oracle: ag-2460..2468 MD3 are upright despite joining source nodes;
    // their controls also terminate a DC path. The first deck is their
    // common six-card local topology. ag-236 M1 is an upright common-gate
    // stage. Rail-gated and diode-connected forms do not establish this
    // source-degeneration habit; a caller's upright instruction wins.
    const lib = try support.library(testing.allocator);
    defer support.freeLibrary(testing.allocator, lib);
    const decks = [_][]const u8{
        models ++ "M25 net8 VC VZ VSS nch\nMD4 net0 VB4 net9 VSS nch\n" ++
            "M14 VZ net8 VSS VSS nch\nMD2 net9 VB2 VSS VSS nch\n" ++
            "MD1 VA net1 VSS VSS nch\nMX VZ VA net9 VSS nch\n",
        models ++ "MX Iout Vb Iin VSS nch\n",
        models ++ pair ++ "MX b vss a vss nch\n",
        models ++ pair ++ "MX b b a vss nch\n",
        models ++ pair ++ "MX b a a vss nch\n",
        models ++ pair ++ "MX b control a vss nch\n*@ upright mx\n",
        models ++ "M1 out_a input_a a vss nch\nM2 out_b input_b b vss nch\n" ++
            "I1 a vss 1m\nI2 b remote 1m\nMX b control a vss nch\n",
        models ++ pair ++ "MX b control a vdd pch\n",
    };
    for (decks) |deck| {
        var p = try np.place(testing.allocator, &.default, lib, &.{deck}, null);
        defer p.deinit();
        try testing.expectEqual(pin(&p, "mx", 0).x, pin(&p, "mx", 2).x);
        try testing.expect(pin(&p, "mx", 0).y != pin(&p, "mx", 2).y);
        try support.expectConnected(&p, lib);
    }
}

#!/usr/bin/env python3
"""Replay named research certificates; no compiler or production test claim.

Every command has its own output, exit status and captured log. The suite
continues after a failure to preserve its exact failing-name set, then exits
nonzero. Existing reference evidence is never regenerated by this runner.
"""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import time

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
RUN = ROOT / '.objective/human-schematic-equivalence/runs/iteration21-resume1/image-rule-round-2'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write(path, value):
    temporary = path.with_suffix(path.suffix + '.tmp')
    temporary.write_text(json.dumps(value, indent=2, sort_keys=True) + '\n')
    temporary.replace(path)


def cases(output):
    rows = []

    def add(name, script, arguments, reference=None, kind='certificate replay'):
        artifact = output / (name + '.json')
        command = [sys.executable, '-B', str(HERE / script)]
        command += [str(artifact) if x == '{output}' else str(x) for x in arguments]
        if reference:
            command += ['--check', str(reference)]
        rows.append(dict(name=name, command=command, artifact=artifact,
                         script=HERE / script, reference=reference, kind=kind))

    add('complete_visual_review', 'collect_reviews.py', ['--output', '{output}'])
    examples = ROOT / 'external/examples/analoggenie'
    add('source_region_census', 'groups_candidates.py', [examples, '{output}'], RUN / 'groups/census.json')
    add('source_region_contacts', 'groups_evidence.py',
        [examples, RUN / 'groups/native', '{output}'], RUN / 'groups/evidence.json')
    add('body_terminal_census', 'bodies_census.py', ['{output}'], RUN / 'bodies/census.json')
    add('body_source_contacts', 'bodies_examples.py', ['{output}'], HERE / 'bodies_evidence.json')
    add('body_class_contracts', 'bodies_contracts.py', ['{output}'], kind='frozen native CLI plus literal assertions')
    add('substrate_and_attachment_attacks', 'bodies_review_groups.py', ['{output}', '--require-fixed'])
    for name, script, reference in [
        ('port_source_contacts', 'ports_contracts.py', 'ports_contracts.json'),
        ('port_local_predicates', 'ports_predicates.py', 'ports_predicates.json'),
        ('port_frame_feasibility', 'ports_pose.py', 'ports_pose.json'),
        ('port_review_of_bodies', 'ports_review_bodies.py', 'ports_review_bodies.json'),
        ('group_review_of_ports', 'groups_review_ports.py', 'groups_review_ports.json'),
        ('group_review_of_quads', 'groups_review_quads.py', 'groups_review_quads.json'),
        ('contract_selector_composition', 'interaction_candidates.py', 'interaction_candidates.json'),
        ('quad_raw_census', 'quad_candidates.py', 'quad_candidates.json'),
        ('quad_topology_transport', 'quad_equivalence.py', 'quad_equivalence.json'),
        ('wire_angle_census', 'wire_angles.py', 'wire_angles.json'),
        ('additional_port_contacts', 'third-ports-contracts.py', 'third-ports-contracts.json'),
        ('ninth_index_witness', 'third-ports-width.py', 'third-ports-width.json'),
        ('diagonal_independent_geometry', 'third-diagonals-probe.py', 'third-diagonals-probe.json'),
        ('caller_fixture_literal_proof', 'fourth-ports-proof.py', 'fourth-ports-proof.json'),
    ]:
        add(name, script, ['--output', '{output}'], HERE / reference)
    add('body_only_native_replay', 'third-bodies-proof.py',
        ['{output}', '--replay-native'], HERE / 'third-bodies-evidence.json', 'frozen native CLI replay and source certificate')
    add('all_body_only_source_contacts', 'fourth-bodies-proof.py', ['{output}'], HERE / 'fourth-bodies-evidence.json')
    add('external_body_marker_contacts', 'fifth-bodies-proof.py', ['{output}'], HERE / 'fifth-bodies-evidence.json')
    add('caller_fixture_native_replay', 'fourth-ports-fixtures.py',
        ['--execute', '--output', '{output}'], HERE / 'fourth-ports-fixtures.json', 'frozen native CLI replay')
    for name, script, reference in [
        ('independent_caller_frame_review', 'fifth-cross-ports-probe.py', 'fifth-cross-ports-probe.json'),
        ('final_group_relation_proof', 'sixth-groups-proof.py', 'sixth-groups-proof.json'),
        ('digital_and_box_source_proof', 'sixth-symbols-proof.py', 'sixth-symbols-proof.json'),
        ('hidden_body_ink_review', 'seventh-review-bodies-probe.py', 'seventh-review-bodies-probe.json'),
    ]:
        add(name, script, ['--output', '{output}'], HERE / reference)
    add('final_group_relation_native_replay', 'sixth-groups-fixtures.py',
        ['--execute', '--output', '{output}'], HERE / 'sixth-groups-fixtures.json', 'frozen native CLI replay')
    add('hidden_body_peer_native_replay', 'sixth-bodies-proof.py',
        ['{output}'], HERE / 'sixth-bodies-evidence.json', 'frozen native CLI replay and actual ink certificate')
    add('digital_and_box_native_replay', 'sixth-symbols-fixtures.py',
        ['--execute', '--output', '{output}'], HERE / 'sixth-symbols-fixtures.json', 'frozen native CLI replay')
    add('independent_symbol_native_review', 'seventh-review-symbols.py',
        ['{output}', '--execute', '--require-fixed'], HERE / 'seventh-review-symbols.json',
        'frozen native CLI replay and archived source-proof attacks')
    add('independent_group_native_review', 'seventh-review-groups-proof.py',
        ['--execute', '--output', '{output}'], HERE / 'seventh-review-groups-proof.json',
        'frozen native CLI replay and archived report/raw-card cache attacks')
    add('external_body_visibility_admission', 'eighth-bodies-visibility.py',
        ['{output}'], HERE / 'eighth-bodies-visibility.json')
    add('older_target_export_certificate', 'eighth-target-proof.py',
        ['--output', '{output}'], HERE / 'eighth-target-proof.json',
        'saved actual older-host/plugin exports and comparator controls; no new host execution')
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    output = args.output_dir.resolve()
    output.relative_to(ROOT)
    output.mkdir(parents=True, exist_ok=True)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    rows = cases(output)
    names = [row['name'] for row in rows]
    assert len(names) == len(set(names))
    inputs = sorted({row['script'] for row in rows} |
                    {row['reference'] for row in rows if row['reference']} | {Path(__file__).resolve()})
    before = {str(path.relative_to(ROOT)): sha(path) for path in inputs}
    report = dict(scope='Research evidence replay; no engine build, production test suite, new target host round trip, or equivalence claim. A named certificate checks saved executions of an older host/plugin.',
                  expected_names=names, inputs_before=before, results=[], complete=False)
    write(args.report, report)
    for row in rows:
        start = time.monotonic()
        try:
            result = subprocess.run(row['command'], cwd=ROOT, capture_output=True, text=True, timeout=180)
            status, stdout, stderr = result.returncode, result.stdout, result.stderr
        except subprocess.TimeoutExpired as error:
            status = None
            stdout = (error.stdout or b'').decode(errors='replace') if isinstance(error.stdout, bytes) else (error.stdout or '')
            stderr = 'TIMEOUT after 180 seconds\n' + ((error.stderr or b'').decode(errors='replace') if isinstance(error.stderr, bytes) else (error.stderr or ''))
        logs = {}
        for suffix, value in [('stdout', stdout), ('stderr', stderr)]:
            path = output / (row['name'] + '.' + suffix + '.txt')
            path.write_text(value)
            logs[suffix] = dict(path=str(path.relative_to(ROOT)), sha256=sha(path))
        report['results'].append(dict(name=row['name'], kind=row['kind'], command=row['command'],
            exit_code=status, passed=status == 0, elapsed_seconds=round(time.monotonic() - start, 3),
            artifact=str(row['artifact'].relative_to(ROOT)),
            artifact_sha256=sha(row['artifact']) if row['artifact'].is_file() else None, logs=logs))
        write(args.report, report)
        print(('PASS' if status == 0 else 'FAIL'), row['name'], flush=True)
    after = {str(path.relative_to(ROOT)): sha(path) for path in inputs}
    report.update(inputs_after=after, changed_inputs=sorted(name for name in before if before[name] != after[name]),
                  failed_names=[r['name'] for r in report['results'] if not r['passed']], complete=True)
    assert names == [r['name'] for r in report['results']]
    report['passed'] = not report['failed_names'] and not report['changed_inputs']
    write(args.report, report)
    print(json.dumps({k: report[k] for k in ['complete', 'passed', 'failed_names', 'changed_inputs']}))
    raise SystemExit(0 if report['passed'] else 1)


if __name__ == '__main__':
    main()

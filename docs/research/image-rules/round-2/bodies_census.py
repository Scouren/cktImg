#!/usr/bin/env python3
"""Frozen 2,202 DUT decks -> ordered raw incidence and body relationship census.

Research only. No production selector or geometry inference. Model/definition
arity is read before cards; every terminal occurrence, including repeated nets,
survives. Source rail annotations are evidence fields, not inferred semantics.
"""
import argparse
import collections
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
BASE = ROOT / '.objective/human-schematic-equivalence/runs/iteration21-resume1'
AUDIT = BASE / 'image-rule-audit'
SELECTED = [937, 939, 1014, 1021, 1022, 1026, 1057, 1065, 1076, 1102,
            1124, 1128, 1130, 1160, 1167, 1169, 1177, 1181, 1294, 1333]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def parse(text):
    """Return complete DUT formal/card rows; unsupported card kinds fail loudly."""
    lines = []
    for source in text.splitlines():
        line = source.strip()
        if not line or line.startswith('*'):
            continue
        if line.startswith('+'):
            assert lines, 'orphan continuation'
            lines[-1] += ' ' + line[1:]
        else:
            lines.append(line)
    models, definitions = set(), {}
    for line in lines:
        t = line.lower().split()
        if t[0] == '.model':
            models.add(t[1])
        elif t[0] == '.subckt':
            ports = []
            for word in t[2:]:
                if word == 'params:' or '=' in word:
                    break
                ports.append(word)
            definitions[t[1]] = ports
    assert 'dut' in definitions
    active, rows = False, []
    for line in lines:
        t = line.lower().split()
        if t[0] == '.subckt':
            active = t[1] == 'dut'
        elif t[0] == '.ends':
            active = False
        elif active and not t[0].startswith('.'):
            kind = t[0][0]
            if kind in 'rcldiv':
                count, roles = 2, ['1', '2']
            elif kind == 'm':
                count, roles = 4, ['D', 'G', 'S', 'B']
                assert t[5] in models
            elif kind == 'q':
                places = [i for i in (4, 5) if i < len(t) and t[i] in models]
                assert len(places) == 1, line
                count = places[0] - 1
                roles = ['C', 'B', 'E', 'substrate'][:count]
            elif kind in 'sg':
                count, roles = 4, ['1', '2', 'control1', 'control2']
            elif kind == 'x':
                end = next((i for i, w in enumerate(t) if '=' in w or w == 'params:'), len(t))
                name = t[end - 1]
                assert name in definitions, line
                count, roles = len(definitions[name]), definitions[name]
                assert end == count + 2, line
            elif kind == 'k':
                count, roles = 0, []  # inductor references, not electrical nodes
            else:
                raise AssertionError(('unsupported DUT card', line))
            assert len(t) >= count + 2, line
            rows.append(dict(card=t[0], kind=kind, nets=t[1:1+count], roles=roles,
                             raw=line, nonterminal_tokens=t[1+count:]))
    assert len(rows) == len({r['card'] for r in rows})
    return definitions['dut'], rows


def incidence(rows):
    result = collections.defaultdict(list)
    for row in rows:
        for index, (role, net) in enumerate(zip(row['roles'], row['nets'])):
            result[net].append([row['card'], index, role])
    return dict(sorted(result.items()))


def relation(nets):
    d, g, s, b = nets
    # The order deliberately preserves the all-tied varactor as B=S.
    return 'B=S' if b == s else 'B=D' if b == d else 'B=G' if b == g else 'B=distinct'


def ties(nets):
    d, g, s, b = nets
    return {'B=D': b == d, 'B=G': b == g, 'B=S': b == s, 'D=S': d == s}


def binding_check(text, expected):
    """Compare parsed ordered card bindings against an independent literal oracle."""
    _, rows = parse(text)
    actual = {r['card']: r['nets'] for r in rows}
    for card, pins in expected.items():
        assert actual[card] == pins, (card, actual[card], pins)


def checks():
    # Independent literals read from the actual cards, not generated by the parser.
    literal = {
        'ag-1014': {'m1': ['vout1', 'vdd', 'net1', 'vi1'], 'm2': ['vout2', 'vdd', 'net1', 'vi2']},
        'ag-1021': {'m1': ['net0', 'vdd', 'vss', 'net0'], 'm2': ['iout', 'vdd', 'vss', 'net0']},
        'ag-1128': {'m1': ['out+', 'out-', 'net0', 'net0']},
        'ag-1130': {'m3': ['nc0001', 'vout1', 'nc0002', 'vtune']},
        'ag-1167': {'m1': ['net7', 'net3', 'vss', 'net0'], 'm5': ['net14', 'net8', 'net6', 'net9']},
        'ag-1177': {'m3': ['vctrl', 'net1', 'vctrl', 'vctrl']},
        'ag-1294': {'m1': ['vx1', 'vcont2', 'vin', 'vin'], 'mp7': ['vx2', 'vref', 'net2', 'net4']},
    }
    for ident, expected in literal.items():
        binding_check((ROOT/'external/examples/analoggenie'/f'{ident}.cir').read_text(), expected)
    cases = [(['d', 'g', 's', 's'], 'B=S'), (['d', 'g', 's', 'd'], 'B=D'),
             (['d', 'g', 's', 'g'], 'B=G'), (['d', 'g', 's', 'b'], 'B=distinct'),
             (['v', 'g', 'v', 'v'], 'B=S')]
    for pins, expected in cases:
        assert relation(pins) == expected
        rename = {n: f'anonymous_{i}' for i, n in enumerate(sorted(set(pins)))}
        assert relation([rename[n] for n in pins]) == expected
        assert ties([rename[n] for n in pins]) == ties(pins)
    assert ties(['v', 'g', 'v', 'v']) == {'B=D': True, 'B=G': False, 'B=S': True, 'D=S': True}
    _, rows = parse('t\n.model nm nmos\n.subckt dut a b\nM1 a b b b nm\nR1 b a 1k\n.ends dut')
    assert incidence(rows)['b'] == [['m1', 1, 'G'], ['m1', 2, 'S'], ['m1', 3, 'B'], ['r1', 0, '1']]
    assert sorted(incidence(list(reversed(rows)))['b']) == sorted(incidence(rows)['b'])
    # Run the same parser + literal binding checker on actual mutated input.
    deck = (ROOT/'external/examples/analoggenie/ag-1014.cir').read_text()
    lines = deck.splitlines()
    index = next(i for i, line in enumerate(lines) if line.lower().split()[:1] == ['m1'])
    original = lines[index].split()
    mutations = {}
    for name in ('drop_B', 'swap_G_B', 'replace_B_with_S'):
        tokens = original.copy()
        if name == 'drop_B': del tokens[4]
        elif name == 'swap_G_B': tokens[2], tokens[4] = tokens[4], tokens[2]
        else: tokens[4] = tokens[3]
        altered = lines.copy(); altered[index] = ' '.join(tokens)
        try:
            binding_check('\n'.join(altered), literal['ag-1014'])
        except (AssertionError, IndexError) as error:
            mutations[name] = type(error).__name__
        else:
            raise AssertionError(('mutation survived', name))
    return dict(literal_cards=literal, relation_cases=[list(case) for case in cases], rename_invariant=True,
                repeated_occurrences_preserved=True, reordered_cards_invariant=True,
                simultaneous_ties_preserved=True, mutated_deck_rejections=mutations)


def census():
    assignment = [r for i in range(3) for r in json.loads((AUDIT/f'shard-{i}.json').read_text())['images']]
    assert len(assignment) == 2202
    assert len({r['id'] for r in assignment}) == 2202
    circuits, buckets, kinds = [], collections.defaultdict(list), collections.Counter()
    for item in assignment:
        path = Path(item['netlist']); assert sha(path) == item['netlist_sha256']
        ports, rows = parse(path.read_text()); inc = incidence(rows)
        human = json.loads(Path(item['source_json']).read_text())
        rails = sorted({m['net'].lower() for m in human['markers'] if m.get('net') and m.get('kind') in ('supply', 'ground')})
        mos = []
        for row in rows:
            kinds[row['kind']] += 1
            if row['kind'] != 'm':
                continue
            b = row['nets'][3]; rel = relation(row['nets'])
            nonbody = [p for p in inc[b] if not (p[0][0] == 'm' and p[1] == 3)]
            entry = dict(card=row['card'], pins=row['nets'], relation=rel, ties=ties(row['nets']),
                         body_formal=b in ports, source_rail_annotation=b in rails,
                         body_incidence=inc[b], body_nonbody_incidence=nonbody)
            mos.append(entry)
            buckets[rel].append([item['id'], row['card']])
            if rel != 'B=S' and b not in rails:
                buckets['nonself_without_source_rail'].append([item['id'], row['card']])
            if rel == 'B=distinct' and not nonbody and b not in ports:
                buckets['internal_body_only'].append([item['id'], row['card']])
        circuits.append(dict(id=item['id'], netlist_sha256=sha(path), source_json_sha256=sha(Path(item['source_json'])),
                             formals=ports, source_rail_nets=rails, rows=rows, incidence=inc, mos=mos))
    return dict(scope='Exact 2202 assigned DUT decks; subcircuit definitions supply arity but are not flattened. No extra image-view claim.',
                script_sha256=sha(Path(__file__)), checks=checks(), counts=dict(kinds),
                buckets=dict(buckets), circuits=circuits)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('output', type=Path); ap.add_argument('--check', type=Path)
    args = ap.parse_args(); result = census()
    if args.check:
        assert result == json.loads(args.check.read_text()), 'named census changed'
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2)+'\n')
    selected = [c for c in result['circuits'] if int(c['id'][3:]) in SELECTED]
    args.output.with_name('bodies_selected.json').write_text(json.dumps(selected, indent=2)+'\n')
    print({k: len(v) for k, v in result['buckets'].items()})
    print('PASS exact 2202 names; all DUT terminal occurrences; literal and mutation controls')


if __name__ == '__main__':
    main()
